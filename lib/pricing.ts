const FALLBACK_BY_TIER: Record<string, number> = TIER_FALLBACK;

export function getMsrp(
  brandSlug: string,
  model: string,
  tierFallback: keyof typeof TIER_FALLBACK,
): number {
  const rules = MODEL_PRICING[brandSlug] ?? [];
  for (const rule of rules) {
    if (rule.test.test(model)) return rule.msrp;
  }
  return FALLBACK_BY_TIER[tierFallback] ?? 25000;
}

export function computeCarPrice(
  brandSlug: string,
  model: string,
  year: number,
  tierFallback: keyof typeof TIER_FALLBACK,
): number {
  const msrp = getMsrp(brandSlug, model, tierFallback);
  const currentYear = new Date().getFullYear();
  const age = Math.max(0, currentYear - year);
  const factor = Math.max(0.2, Math.pow(0.92, age));
  return Math.round((msrp * factor) / 100) * 100;
}
